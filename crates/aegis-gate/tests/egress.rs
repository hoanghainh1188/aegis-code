//! #66: the fetch step downloads through the egress proxy and nothing
//! else; the gate then builds offline from what it fetched, mounted
//! read-only. Needs Docker, the network and both sandbox images
//! (`docker/rust`, `docker/python`); skipped otherwise, unless
//! `AEGIS_REQUIRE_DOCKER=1`.

use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Duration;

use aegis_gate::{CancelToken, Egress, Exit, Hardening, Limits, Runner, Sandbox};

const RUST_IMAGE: &str = "aegis-sandbox-rust";
const PYTHON_IMAGE: &str = "aegis-sandbox-python";
const TIMEOUT: Duration = Duration::from_secs(300);

fn docker_ready() -> bool {
    let ok = [RUST_IMAGE, PYTHON_IMAGE].iter().all(|image| {
        Command::new("docker")
            .args(["image", "inspect", image])
            .output()
            .is_ok_and(|o| o.status.success())
    });
    if !ok {
        assert!(
            std::env::var("AEGIS_REQUIRE_DOCKER").as_deref() != Ok("1"),
            "docker or a sandbox image is missing"
        );
        eprintln!("skipping: docker or a sandbox image is missing");
    }
    ok
}

fn scratch(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("aegis-egress-{}-{name}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

fn egress(allow: &[&str]) -> Egress {
    Egress {
        docker: "docker".into(),
        proxy_image: PYTHON_IMAGE.into(),
        allow: allow.iter().map(|h| (*h).to_owned()).collect(),
    }
}

/// The image's container, locked down as its profile's are (#320).
fn sandbox(image: &str, mounts: Vec<(PathBuf, String)>) -> Sandbox {
    let language = match image {
        RUST_IMAGE => aegis_lang::Language::Rust,
        _ => aegis_lang::Language::Python,
    };
    let profile = aegis_lang::Profiles::builtin().unwrap();
    let profile = &profile.get(language).unwrap().sandbox;
    Sandbox {
        docker: "docker".into(),
        image: image.into(),
        mounts,
        env: vec![],
        network: None,
        read_only_mounts: true,
        hardening: Hardening::new(Limits::default(), profile),
    }
}

fn argv(words: &[&str]) -> Vec<String> {
    words.iter().map(|w| (*w).to_owned()).collect()
}

fn log_of(path: &Path) -> String {
    std::fs::read_to_string(path).unwrap_or_default()
}

const CARGO_TOML: &str = r#"[package]
name = "probe"
version = "0.1.0"
edition = "2021"

[dependencies]
itoa = "=1.0.18"
"#;

const CARGO_LOCK: &str = r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "itoa"
version = "1.0.18"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "8f42a60cbdf9a97f5d2305f08a87dc4e09308d1276d28c869c684d7777685682"

[[package]]
name = "probe"
version = "0.1.0"
dependencies = [
 "itoa",
]
"#;

#[test]
fn a_rust_crate_fetches_through_the_proxy_and_builds_offline() {
    if !docker_ready() {
        return;
    }
    let dir = scratch("rust");
    let tree = dir.join("tree");
    std::fs::create_dir_all(tree.join("src")).unwrap();
    std::fs::write(tree.join("Cargo.toml"), CARGO_TOML).unwrap();
    std::fs::write(tree.join("Cargo.lock"), CARGO_LOCK).unwrap();
    std::fs::write(
        tree.join("src/lib.rs"),
        "pub fn show(n: u32) -> String { itoa::Buffer::new().format(n).to_owned() }\n",
    )
    .unwrap();
    let registry = dir.join("registry");
    std::fs::create_dir_all(&registry).unwrap();
    let sandbox = sandbox(
        RUST_IMAGE,
        vec![(registry.clone(), "/usr/local/cargo/registry".into())],
    );

    let session = egress(&["index.crates.io", "static.crates.io"])
        .start()
        .unwrap();
    let fetch_log = dir.join("fetch.log");
    let ran = session
        .fetch(
            &sandbox,
            &argv(&["cargo", "fetch", "--locked"]),
            &tree,
            &fetch_log,
            TIMEOUT,
            CancelToken::new(),
        )
        .unwrap();
    let proxy_log = session.log();
    assert_eq!(
        ran.exit,
        Exit::Code(0),
        "{}\n{proxy_log}",
        log_of(&fetch_log)
    );
    assert!(proxy_log.contains("allow static.crates.io"), "{proxy_log}");
    drop(session);

    // The gate's side: no network, the registry read-only.
    let build_log = dir.join("build.log");
    let runner = Runner {
        env: vec![("CARGO_TARGET_DIR".into(), "/work/target".into())],
        timeout: TIMEOUT,
        cancel: CancelToken::new(),
        sandbox: Some(sandbox),
    };
    let built = runner
        .run(
            &argv(&["cargo", "build", "--offline", "--locked"]),
            &tree,
            &build_log,
            &[],
        )
        .unwrap();
    assert_eq!(built.exit, Exit::Code(0), "{}", log_of(&build_log));
    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn python_installs_through_the_proxy_and_other_hosts_are_refused() {
    if !docker_ready() {
        return;
    }
    let dir = scratch("python");
    let tree = dir.join("tree");
    std::fs::create_dir_all(&tree).unwrap();
    let cache = dir.join("uv-cache");
    std::fs::create_dir_all(&cache).unwrap();
    let sandbox = sandbox(PYTHON_IMAGE, vec![(cache, "/home/aegis/.cache/uv".into())]);
    let session = egress(&["pypi.org", "files.pythonhosted.org"])
        .start()
        .unwrap();
    let run = |name: &str, words: &[&str]| {
        let log = dir.join(name);
        let ran = session
            .fetch(
                &sandbox,
                &argv(words),
                &tree,
                &log,
                TIMEOUT,
                CancelToken::new(),
            )
            .unwrap();
        (ran.exit, log_of(&log))
    };

    let (exit, log) = run(
        "install.log",
        &[
            "sh",
            "-c",
            "uv venv -q .venv && uv pip install -q --python .venv/bin/python six==1.17.0 \
             && .venv/bin/python -c 'import six; print(six.__version__)'",
        ],
    );
    assert_eq!(exit, Exit::Code(0), "{log}\n{}", session.log());
    assert!(log.contains("1.17.0"), "{log}");

    // Through the proxy, a host off the list is refused.
    let (exit, log) = run(
        "denied.log",
        &[
            "python",
            "-c",
            "import urllib.request; urllib.request.urlopen('https://example.com', timeout=20)",
        ],
    );
    assert_ne!(exit, Exit::Code(0), "{log}");
    assert!(log.contains("403"), "{log}");
    // Around the proxy, the internal network has no way out.
    let (exit, log) = run(
        "direct.log",
        &[
            "python",
            "-c",
            "import socket; socket.create_connection(('1.1.1.1', 443), timeout=10)",
        ],
    );
    assert_ne!(exit, Exit::Code(0), "{log}");
    let proxy_log = session.log();
    assert!(
        proxy_log.contains("allow files.pythonhosted.org"),
        "{proxy_log}"
    );
    assert!(proxy_log.contains("deny example.com:443"), "{proxy_log}");
    drop(session);
    let _ = std::fs::remove_dir_all(&dir);
}

/// #159: the Rust profile's `cargo deny` runs through a proxy to its
/// `audit_hosts` only (advisory-db on github.com), with the repo's
/// licenses in the deny config the gate writes.
#[test]
fn the_rust_audit_reaches_its_advisory_database_through_the_proxy() {
    if !docker_ready() {
        return;
    }
    let dir = scratch("audit");
    let tree = dir.join("tree");
    std::fs::create_dir_all(tree.join("src")).unwrap();
    // The repo's own crate is not published, so its license is not checked.
    let manifest = CARGO_TOML.replace(
        "edition = \"2021\"\n",
        "edition = \"2021\"\npublish = false\n",
    );
    std::fs::write(tree.join("Cargo.toml"), manifest).unwrap();
    std::fs::write(tree.join("Cargo.lock"), CARGO_LOCK).unwrap();
    std::fs::write(tree.join("src/lib.rs"), "").unwrap();
    let registry = dir.join("registry");
    std::fs::create_dir_all(&registry).unwrap();
    let policy = dir.join("policy");
    std::fs::create_dir_all(&policy).unwrap();
    let sandbox = sandbox(
        RUST_IMAGE,
        vec![
            (registry, "/usr/local/cargo/registry".into()),
            (policy.clone(), "/aegis-audit".into()),
        ],
    );
    let profile = aegis_lang::Profiles::builtin()
        .unwrap()
        .get(aegis_lang::Language::Rust)
        .unwrap()
        .clone();
    let hosts: Vec<&str> = profile
        .dependencies
        .audit_hosts
        .iter()
        .map(String::as_str)
        .collect();
    let audit = profile.dependencies.audit.clone().unwrap();
    let argv = audit
        .render(&[
            (aegis_lang::Placeholder::LockfileDir, "."),
            (
                aegis_lang::Placeholder::DenyConfig,
                "/aegis-audit/deny.toml",
            ),
        ])
        .unwrap();
    let run = |licenses: &[&str], name: &str| {
        let licenses: Vec<String> = licenses.iter().map(|l| (*l).to_owned()).collect();
        let config = aegis_lang::deny_config(Some(&licenses), &[]).unwrap();
        std::fs::write(policy.join("deny.toml"), config).unwrap();
        let session = egress(&hosts).start().unwrap();
        let log = dir.join(format!("{name}.log"));
        let ran = session
            .fetch(&sandbox, &argv, &tree, &log, TIMEOUT, CancelToken::new())
            .unwrap();
        (ran.exit, log_of(&log), session.log())
    };

    // itoa is `MIT OR Apache-2.0`.
    let (exit, log, proxy) = run(&["MIT"], "allowed");
    assert_eq!(exit, Exit::Code(0), "{log}\n{proxy}");
    assert!(proxy.contains("allow github.com"), "{proxy}");
    let (exit, log, _) = run(&["ISC"], "refused");
    assert_ne!(exit, Exit::Code(0), "{log}");
    assert!(log.contains("itoa"), "{log}");
    let _ = std::fs::remove_dir_all(&dir);
}

/// #191: the Python profile's `osv-scanner` runs in its sandbox image
/// through a proxy to its `audit_hosts` only (OSV advisories, deps.dev
/// licenses), with the repo's licenses on the command line.
#[test]
fn the_python_audit_reaches_osv_and_deps_dev_through_the_proxy() {
    if !docker_ready() {
        return;
    }
    let dir = scratch("osv");
    let tree = dir.join("tree");
    std::fs::create_dir_all(&tree).unwrap();
    std::fs::write(tree.join("requirements.txt"), "six==1.17.0\n").unwrap();
    let policy = dir.join("policy");
    std::fs::create_dir_all(&policy).unwrap();
    std::fs::write(
        policy.join("osv-scanner.toml"),
        aegis_lang::osv_config(&[]).unwrap(),
    )
    .unwrap();
    let sandbox = sandbox(PYTHON_IMAGE, vec![(policy, "/aegis-audit".into())]);
    let profile = aegis_lang::Profiles::builtin()
        .unwrap()
        .get(aegis_lang::Language::Python)
        .unwrap()
        .clone();
    let hosts: Vec<&str> = profile
        .dependencies
        .audit_hosts
        .iter()
        .map(String::as_str)
        .collect();
    let audit = profile.dependencies.audit.clone().unwrap();
    let run = |licenses: &str, name: &str| {
        let argv = audit
            .render(&[
                (aegis_lang::Placeholder::Lockfile, "requirements.txt"),
                (aegis_lang::Placeholder::Licenses, licenses),
                (
                    aegis_lang::Placeholder::OsvConfig,
                    "/aegis-audit/osv-scanner.toml",
                ),
            ])
            .unwrap();
        let session = egress(&hosts).start().unwrap();
        let log = dir.join(format!("{name}.log"));
        let ran = session
            .fetch(&sandbox, &argv, &tree, &log, TIMEOUT, CancelToken::new())
            .unwrap();
        (ran.exit, log_of(&log), session.log())
    };

    // six 1.17.0 is MIT and has no known advisory.
    let (exit, log, proxy) = run("MIT", "allowed");
    assert_eq!(exit, Exit::Code(0), "{log}\n{proxy}");
    assert!(proxy.contains("allow api.osv.dev"), "{proxy}");
    assert!(proxy.contains("allow api.deps.dev"), "{proxy}");
    assert!(!proxy.contains("deny"), "{proxy}");
    let (exit, log, _) = run("ISC", "refused");
    assert_ne!(exit, Exit::Code(0), "{log}");
    assert!(log.contains("six"), "{log}");
    assert!(log.contains("LICENSE VIOLATION"), "{log}");
    let _ = std::fs::remove_dir_all(&dir);
}

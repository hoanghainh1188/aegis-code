-- Tenants (#525, ADR 0011): an AMS contract whose repos, people, budget,
-- secrets and disk are kept apart from every other's. Every repo belongs
-- to exactly one; those registered before belong to `default` (id 1),
-- which keeps today's paths and secret names. Expand only: an older server
-- ignores the tables and the column, and runs every repo as before.

CREATE TABLE tenants (
    id                  bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    slug                text NOT NULL UNIQUE
                        CHECK (slug ~ '^[a-z0-9][a-z0-9-]{0,62}$'),
    name                text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 200),
    -- The contract's budget per month, over all its repos; NULL: no cap.
    monthly_budget_usd  double precision
                        CHECK (monthly_budget_usd IS NULL OR monthly_budget_usd >= 0),
    -- Its jobs that may run at once, over all its repos; NULL: no cap.
    max_concurrent_jobs integer CHECK (max_concurrent_jobs IS NULL OR max_concurrent_jobs >= 1),
    created_at          timestamptz NOT NULL DEFAULT now()
);

INSERT INTO tenants (id, slug, name) OVERRIDING SYSTEM VALUE VALUES (1, 'default', 'Default');
SELECT setval(pg_get_serial_sequence('tenants', 'id'), 1);

ALTER TABLE repos
    ADD COLUMN tenant_id bigint NOT NULL DEFAULT 1 REFERENCES tenants (id);
CREATE INDEX repos_tenant ON repos (tenant_id);

-- Who administers a tenant: its repos' roles, pauses and budgets, not
-- other tenants', not the platform's.
CREATE TABLE tenant_admins (
    tenant_id bigint NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
    user_id   bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (tenant_id, user_id)
);

-- What `tenant`'s repos spent since the start of the current month in `zone`.
CREATE FUNCTION tenant_month_spent(tenant bigint, zone text) RETURNS double precision
LANGUAGE sql STABLE AS $$
    SELECT coalesce(sum(e.cost_usd), 0)
    FROM ledger_events e
    JOIN jobs j ON j.ledger_key = e.ledger_key
    JOIN repos r ON r.id = j.repo_id
    WHERE r.tenant_id = tenant
      AND e.recorded_at >= date_trunc('month', now() AT TIME ZONE zone) AT TIME ZONE zone
$$;
